// 供体抽取：node tools/vendor.mjs gl [--check] [--cdp]
//   把 goodGL.html（单文件、经典脚本、全局名互相引用）按 `// ==== xxx.js` 分段标记切成 ESM，写进 vendor/gl/。
//   - 供体文本原样搬运（不重排、不改写）；只加 import / export 头。需要改供体的地方以后走 PATCHES（// remix:），这里还没有。
//   - GLSL 是靠给 GLSL 对象依次重新赋值拼出来的（shaders / shaders2 / shaders3 三段，后面的覆盖前面的，
//     还有三处 .replace 补丁）：这里在 Node 里按原顺序求值，输出求值后的字符串（glsl.js）。
//   - WorkerPool 靠 SHARED_SRC.toString() 塞进 Blob Worker：换成模块 Worker（worker.js 直接 import shared.js）。
//   --check  只检查：重新生成并与磁盘上的 vendor/gl 逐字节比较，再验自由变量都有出处
//   --cdp    验收：启动 Chromium 载入 goodGL.html，dump 运行时的 GLSL 对象，与 glsl.js 逐字符比较
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = resolve(ROOT, 'goodGL.html');
const OUT = resolve(ROOT, 'vendor/gl');
const args = process.argv.slice(2);
if (args[0] !== 'gl') { console.error('usage: vendor.mjs gl [--check] [--cdp]'); process.exit(2); }

const html = readFileSync(SRC, 'utf8');
const m = html.match(/<script>\n([\s\S]*)<\/script>/);
if (!m) throw new Error('goodGL.html: 找不到 <script>');
const code = m[1];

// ---- 分段：`// ==== name.js` 起到下一个标记之前
const seg = {};
{
  const re = /^\/\/ ==== (\S+)\.js$/gm; const marks = [];
  for (let r; (r = re.exec(code));) marks.push({ name: r[1], at: r.index, body: r.index + r[0].length + 1 });
  marks.forEach((k, i) => { seg[k.name] = code.slice(k.body, i + 1 < marks.length ? marks[i + 1].at : code.length).replace(/\s+$/, '') + '\n'; });
}
for (const k of ['shared', 'mathx', 'textures', 'pbr', 'world', 'shaders', 'shaders2', 'shaders3', 'atmos', 'renderer'])
  if (!seg[k]) throw new Error('缺少分段 ' + k);

const HEAD = '// GENERATED by tools/vendor.mjs gl from goodGL.html —— 不要手改；要改供体走 PATCHES（// remix:）\n';

// ---- shared.js：SHARED_SRC 函数体 → 立即求值导出 SH（主线程和模块 Worker 共用）
const shared = (() => {
  const s = seg.shared;
  const a = s.indexOf('const SHARED_SRC = function () {'), b = s.lastIndexOf('};\n\nconst SH = SHARED_SRC();');
  if (a < 0 || b < 0) throw new Error('shared: 找不到 SHARED_SRC / SH 边界');
  const body = s.slice(a + 'const SHARED_SRC = function () {'.length, b);
  return `export const SH = (function () {${body}})();\n`;
})();

// ---- mathx.js：M4 + 3x3 小函数
const mathx = seg.mathx;

// ---- world.js 里只有 WorkerPool 需要（Chunk / World / Store 不取）
const pool = (() => {
  const s = seg.world;
  const a = s.indexOf('class WorkerPool {'), b = s.indexOf('// RLE ---');
  if (a < 0 || b < 0) throw new Error('world: 找不到 WorkerPool 边界');
  let cls = s.slice(a, b).replace(/\s+$/, '') + '\n';
  // Blob Worker → 模块 Worker（三行：src / url / new Worker(url)）
  const i0 = cls.indexOf("      const src = 'const SH=(' + SHARED_SRC.toString()"), i1 = cls.indexOf("      for (let i = 0; i < n; i++) {");
  if (i0 < 0 || i1 < 0) throw new Error('WorkerPool: 找不到 Blob Worker 片段');
  cls = cls.slice(0, i0) + cls.slice(i1).replace('const w = new Worker(url);', "const w = new Worker(new URL('./worker.js', import.meta.url), { type: 'module' });");
  if (!cls.includes("type: 'module'")) throw new Error('WorkerPool: new Worker 没替换');
  return cls;
})();
// 模块 Worker：消息协议与原 Blob 字符串里的一致（init / gen / mesh）
const worker = `import { SH } from './shared.js';
let GEN = null; const OB = new SH.MeshBuilder(16384), TB = new SH.MeshBuilder(4096);
onmessage = function (e) {
  const d = e.data;
  if (d.type === 'init') { GEN = new SH.Generator(d.seed); postMessage({ ready: 1 }); return; }
  if (d.type === 'gen') { const r = GEN.generate(d.cx, d.cz); postMessage({ id: d.id, r }, [r.blocks.buffer, r.meta.buffer]); }
  else if (d.type === 'mesh') {
    const r = SH.meshSection(d.pb, d.pm, d.pl, d.tg, d.tf, d.wx, d.wy, d.wz, OB, TB);
    const tr = []; if (r.opaque) tr.push(r.opaque); if (r.trans) tr.push(r.trans);
    postMessage({ id: d.id, r }, tr);
  }
};
`;

// ---- glsl.js：按原顺序求值（只自引用 GLSL.*，没有别的外部名）
const glslText = seg.shaders + seg.shaders2 + seg.shaders3;
const GLSL = new Function(glslText + '\nreturn GLSL;')();
const esc = s => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const glsl = `export const GLSL = {\n` + Object.entries(GLSL).map(([k, v]) => `${k}: \`${esc(v)}\`,\n`).join('') + `};\n`;

// ---- 其余模块：原文 + import / export 头。导出名与依赖由下面的扫描决定
const mods = {
  'textures.js': { text: seg.textures, exp: ['Textures'] },
  'pbr.js':      { text: seg.pbr,      exp: ['PBR'] },
  'atmos.js':    { text: seg.atmos,    exp: ['Atmos'] },
  'renderer.js': { text: seg.renderer, exp: ['Renderer'] },
  'pool.js':     { text: pool,         exp: ['WorkerPool'] },
};
const PROVIDES = {                       // 全局名 → 提供它的模块
  SH: 'shared.js', M4: 'mathx.js', rotX: 'mathx.js', rotY: 'mathx.js', rotZ: 'mathx.js', m3mul: 'mathx.js', m3v: 'mathx.js',
  Textures: 'textures.js', PBR: 'pbr.js', Atmos: 'atmos.js', GLSL: 'glsl.js', Renderer: 'renderer.js', WorkerPool: 'pool.js',
};
const strip = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:\\])\/\/.*$/gm, '$1');
const idents = s => new Set(strip(s).replace(/\.\s*[A-Za-z_$][\w$]*/g, '.').match(/[A-Za-z_$][\w$]*/g));   // 属性访问（S.tex）不算引用

// 供体里所有顶层名（用来发现"用了但没提供"的全局，例如 Game / World）
const toplevel = new Set([...code.replace(seg.shared, '').matchAll(/^(?:const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/gm)].map(r => r[1]));
const unresolved = [];

const files = { 'shared.js': HEAD + shared, 'mathx.js': HEAD + mathx.replace(/^const M4 =/m, 'export const M4 =').replace(/^function (rotX|rotY|rotZ|m3mul|m3v)\(/gm, 'export function $1('), 'glsl.js': HEAD + glsl, 'worker.js': HEAD + worker };
for (const [file, { text, exp }] of Object.entries(mods)) {
  const ids = idents(text);
  const need = {};
  for (const [name, from] of Object.entries(PROVIDES)) if (from !== file && ids.has(name)) (need[from] ||= []).push(name);
  const imports = Object.entries(need).map(([from, names]) => `import { ${names.join(', ')} } from './${from}';\n`).join('');
  // 供体里的顶层名没有被提供、却被引用：记下来
  for (const t of toplevel) if (!(t in PROVIDES) && ids.has(t) && !new RegExp(`^(?:const|let|var|function|class)\\s+${t}\\b`, 'm').test(text) && !exp.includes(t)) unresolved.push(`${file}: ${t}`);
  // 顶层声明加 export（const X = … / class X {…}）
  let body = text;
  for (const n of exp) {
    const re = new RegExp(`^(const|class) ${n}\\b`, 'm');
    if (!re.test(body)) throw new Error(`${file}: 找不到顶层声明 ${n}`);
    body = body.replace(re, 'export $1 ' + n);
  }
  files[file] = HEAD + imports + body;
}
files['index.js'] = HEAD + ['shared', 'mathx', 'glsl', 'textures', 'pbr', 'atmos', 'pool', 'renderer'].map(f => `export * from './${f}.js';\n`).join('');

if (unresolved.length) { console.error('自由变量没有出处（要补 PROVIDES 或评估是否取）：\n  ' + unresolved.join('\n  ')); process.exit(1); }

// ---- 写 / 检
if (args.includes('--check')) {
  let bad = 0;
  for (const [f, t] of Object.entries(files)) {
    const p = resolve(OUT, f);
    if (!existsSync(p) || readFileSync(p, 'utf8') !== t) { console.error('DIFF', f); bad++; }
  }
  console.log(bad ? `FAIL ${bad} 个文件与重新生成的不同` : `OK ${Object.keys(files).length} 个文件与重新生成的一致`);
  if (bad) process.exit(1);
} else {
  mkdirSync(OUT, { recursive: true });
  for (const [f, t] of Object.entries(files)) writeFileSync(resolve(OUT, f), t);
  console.log('写入 vendor/gl/: ' + Object.entries(files).map(([f, t]) => `${f}(${t.split('\n').length - 1} 行)`).join(' '));
}

// ---- 验收：磁盘上的 glsl.js 与页面运行时的 GLSL 逐字符相等
if (args.includes('--cdp')) {
  const { launch } = await import('./cdp.mjs');
  const { default: http } = await import('node:http');
  const { readFile } = await import('node:fs/promises');
  const srv = http.createServer(async (q, r) => { try { r.end(await readFile(resolve(ROOT, '.' + q.url.split(/[?#]/)[0]))); } catch { r.statusCode = 404; r.end(); } }).listen(0);
  const c = await launch({ tag: 'vendor' });
  try {
    await c.send('Page.navigate', { url: `http://127.0.0.1:${srv.address().port}/goodGL.html#auto&seed=1` });
    for (let i = 0; i < 50; i++) { if (await c.js(`typeof GLSL === 'object' && !!GLSL.fancyFS`).catch(() => false)) break; await new Promise(r => setTimeout(r, 200)); }
    const live = JSON.parse(await c.js('JSON.stringify(GLSL)'));
    const disk = (await import(pathToFileURL(resolve(OUT, 'glsl.js')).href)).GLSL;
    const ks = new Set([...Object.keys(live), ...Object.keys(disk)]); let bad = 0;
    for (const k of ks) if (live[k] !== disk[k]) { console.error('GLSL 不同:', k, live[k]?.length, disk[k]?.length); bad++; }
    console.log(bad ? `FAIL ${bad}/${ks.size}` : `OK GLSL ${ks.size} 项与运行时逐字符相等`);
    if (bad) process.exitCode = 1;
  } finally { c.close(); srv.close(); }
}
