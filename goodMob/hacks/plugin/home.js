// goodMob · start screen model library.
//
// The patched start screen (hacks/patches/0001-*) renders whatever this exposes as `window.goodmobHome`:
//   items()             -> [{key, name, kind, icon, hint, thumb?, source, ...}]  (refreshed by 'goodmob:library')
//   open(item)          -> open a library / folder entry
//   openFolder()        -> directory picker (File System Access API), remembered across reloads
//   dropFiles(fileList) -> .vox / .bbmodel / .svox dropped on the start screen
//   pasteText(text)     -> SVOX text or .bbmodel JSON pasted on the start screen
//
// Plugin-only (no core patch beyond the start screen slot). The built-in library is hacks/library.json, generated by
// scripts/make-library.py; the directory handle lives in IndexedDB, so "recent" survives a reload as long as the
// browser still grants read permission to that folder.
(() => {
  'use strict';
  const ROOT = new URL('../../', document.currentScript.src).href;     // .../goodMob/
  const LIBRARY_URL = ROOT + 'hacks/library.json';
  const KIND_BY_EXT = { '.vox': 'vox', '.bbmodel': 'bbmodel', '.svox': 'svox' };
  const ICON = { vox: 'view_in_ar', svox: 'deployed_code', bbmodel: 'insert_drive_file', folder: 'folder_open' };
  const DB_NAME = 'goodmob_home';
  const STORE = 'handles';

  let items = [];
  let folder = null;          // { handle, name }

  // ---------- IndexedDB: one record, the last directory handle ----------
  const openDB = () => new Promise((resolve, reject) => {
    const req = indexedDB.open(DB_NAME, 1);
    req.onupgradeneeded = () => req.result.createObjectStore(STORE);
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
  async function idbGet(key) {
    try {
      const db = await openDB();
      return await new Promise(resolve => {
        const req = db.transaction(STORE, 'readonly').objectStore(STORE).get(key);
        req.onsuccess = () => resolve(req.result || null);
        req.onerror = () => resolve(null);
      });
    } catch { return null; }
  }
  async function idbSet(key, value) {
    try {
      const db = await openDB();
      await new Promise(resolve => {
        const tx = db.transaction(STORE, 'readwrite');
        tx.objectStore(STORE).put(value, key);
        tx.oncomplete = resolve;
        tx.onerror = resolve;
      });
    } catch { /* private mode: folder is just not remembered */ }
  }

  // ---------- helpers ----------
  const refresh = () => window.dispatchEvent(new Event('goodmob:library'));
  const extOf = name => name.slice(name.lastIndexOf('.')).toLowerCase();
  const looksLikeSvox = text => /^\s*(size|scale|origin|resize|rotation|position|shape|material|define|group|prefab|light|texture|voxels)\b/m.test(text);

  async function svox() {
    for (let i = 0; i < 100 && !window.goodmobSvox; i++) await new Promise(r => setTimeout(r, 100));
    if (!window.goodmobSvox) throw new Error('the SVOX plugin is not loaded');
    return window.goodmobSvox;
  }

  async function openFile(file) {
    const name = file.name || 'model';
    const ext = extOf(name);
    const kind = KIND_BY_EXT[ext];
    if (kind === 'vox') return (await svox()).importVox({ name, content: await file.arrayBuffer() });
    const text = await file.text();
    if (kind === 'bbmodel') return loadModelFile({ name, path: name, content: text });
    return (await svox()).importSvoxText(text, name.replace(/\.svox$/i, ''));
  }

  async function listFolder({ handle, name }, request) {
    if (request && handle.requestPermission) {
      const state = await handle.queryPermission?.({ mode: 'read' });
      if (state !== 'granted') await handle.requestPermission({ mode: 'read' });
    }
    const out = [];
    for await (const [entry_name, entry] of handle.entries()) {
      if (entry.kind !== 'file') continue;
      const kind = KIND_BY_EXT[extOf(entry_name)];
      if (!kind) continue;
      out.push({
        key: `dir:${entry_name}`, name: entry_name, kind, icon: ICON[kind],
        hint: `${name}/${entry_name}`, source: 'dir', handle: entry,
      });
    }
    out.sort((a, b) => a.name.localeCompare(b.name));
    return out;
  }

  const libraryItems = () => items.filter(item => item.source === 'library');
  const folderItems = () => items.filter(item => item.source !== 'library');
  const setFolderItems = list => { items = [...list, ...libraryItems()]; refresh(); };

  // ---------- public API ----------
  const home = {
    items() { return items; },

    async open(item) {
      try {
        if (item.source === 'reopen') {
          folder = { handle: item.handle, name: item.name.replace(/^Reopen /, '') };
          await idbSet('dir', folder);
          return setFolderItems(await listFolder(folder, true));
        }
        if (item.source === 'dir') return openFile(await item.handle.getFile());
        const response = await fetch(ROOT + item.file);
        if (!response.ok) throw new Error(`${item.file}: HTTP ${response.status}`);
        if (item.kind === 'vox') return (await svox()).importVox({ name: item.name, content: await response.arrayBuffer() });
        const text = await response.text();
        if (item.kind === 'bbmodel') return loadModelFile({ name: item.name, path: item.name, content: text });
        return (await svox()).importSvoxText(text, item.name.replace(/\.svox$/i, ''));
      } catch (e) {
        console.error('[goodMob home]', e);
        Blockbench.showQuickMessage(`Could not open ${item.name}: ${e.message || e}`, 4000);
      }
    },

    async openFolder() {
      if (!window.showDirectoryPicker) {
        Blockbench.showQuickMessage('This browser has no File System Access API — use Chrome or Edge', 4000);
        return;
      }
      try {
        const handle = await window.showDirectoryPicker({ mode: 'read' });
        folder = { handle, name: handle.name };
        await idbSet('dir', folder);
        const list = await listFolder(folder, false);
        setFolderItems(list);
        Blockbench.showQuickMessage(`${list.length} models in ${handle.name}`, 2500);
      } catch (e) {
        if (e && e.name !== 'AbortError') console.error('[goodMob home]', e);
      }
    },

    async dropFiles(fileList) {
      const files = [...fileList].filter(f => KIND_BY_EXT[extOf(f.name)] || extOf(f.name) === '.json');
      if (!files.length) {
        Blockbench.showQuickMessage('Drop a .vox, .bbmodel or .svox file', 3000);
        return;
      }
      for (const file of files) {
        try { await openFile(file); } catch (e) { console.error('[goodMob home]', e); Blockbench.showQuickMessage(`Could not open ${file.name}`, 3000); }
      }
    },

    async pasteText(text) {
      if (!text || !text.trim()) return;
      const trimmed = text.trim();
      if (trimmed.startsWith('{')) {
        try {
          const json = JSON.parse(trimmed);
          if (json.meta || json.outliner || json.elements) {
            return loadModelFile({ name: 'clipboard.bbmodel', path: 'clipboard.bbmodel', content: trimmed });
          }
        } catch { /* not JSON: fall through to SVOX */ }
      }
      if (!looksLikeSvox(text)) {
        Blockbench.showQuickMessage('Pasted text is neither SVOX nor a .bbmodel', 3000);
        return;
      }
      try { return (await svox()).importSvoxText(text, 'clipboard'); }
      catch (e) { console.error('[goodMob home]', e); Blockbench.showQuickMessage(`SVOX import failed: ${e.message || e}`, 4000); }
    },
  };
  window.goodmobHome = home;

  // ---------- boot: built-in library + remembered folder ----------
  (async () => {
    let models = [];
    try {
      const response = await fetch(LIBRARY_URL, { cache: 'no-cache' });
      if (response.ok) models = (await response.json()).models || [];
    } catch (e) { console.warn('[goodMob home] no built-in library', e); }

    items = models.map(m => ({
      key: `lib:${m.file}`, name: m.name, kind: m.kind, icon: ICON[m.kind] || 'insert_drive_file',
      hint: m.file, source: 'library', file: m.file,
    }));

    const saved = await idbGet('dir');
    if (saved?.handle) {
      folder = saved;
      const permission = await saved.handle.queryPermission?.({ mode: 'read' }).catch(() => 'prompt');
      if (permission === 'granted') {
        try { items = [...await listFolder(saved, false), ...items]; } catch (e) { console.warn('[goodMob home]', e); }
      } else {
        items = [{ key: 'dir:reopen', name: `Reopen ${saved.name}`, kind: 'folder', icon: ICON.folder, hint: 'Click to grant read access again', source: 'reopen', handle: saved.handle }, ...items];
      }
    }
    refresh();
    console.log(`[goodMob home] ${items.length} library entries`);
  })().catch(e => console.error('[goodMob home]', e));
})();
