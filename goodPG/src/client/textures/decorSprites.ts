const EGG_ROWS = [
  '................',
  '.......12.......',
  '......1122......',
  '.....112223.....',
  '.....1a2223.....',
  '....11222b33....',
  '....12a22223....',
  '....1222a223....',
  '...1222222b33...',
  '...12b2222233...',
  '...122222a233...',
  '...12a2222233...',
  '....12222b34....',
  '.....223334.....',
  '......3344......',
  '................',
];

function eggSprite(base: RGB, spots: RGB): SpriteDef {
  const o = mixc(base, [0, 0, 0], 0.65);
  return {
    rows: EGG_ROWS,
    inks: {
      ...ramp(mixc(base, [255, 255, 255], 0.35), base, mixc(base, [0, 0, 0], 0.2), mixc(base, [0, 0, 0], 0.38), o),
      a: ink(spots, o),
      b: ink(mixc(spots, [0, 0, 0], 0.25), o),
    },
  };
}

