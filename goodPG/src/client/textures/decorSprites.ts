type RGB = readonly [number, number, number];
interface Ink {
  c: RGB;
  o?: RGB;
  bare?: boolean;
}
interface SpriteDef {
  rows: readonly string[];
  inks: Readonly<Record<string, Ink>>;
  holes?: boolean;
}

const ink = (c: RGB, o?: RGB): Ink => ({ c, o });
const ramp = (c1: RGB, c2: RGB, c3: RGB, c4: RGB, o: RGB): Record<string, Ink> => ({
  '1': ink(c1, o), '2': ink(c2, o), '3': ink(c3, o), '4': ink(c4, o),
});
const mixc = (a: RGB, b: RGB, t: number): RGB => [
  Math.round(a[0] + (b[0] - a[0]) * t), Math.round(a[1] + (b[1] - a[1]) * t), Math.round(a[2] + (b[2] - a[2]) * t),
];

const WOOD = ramp([196, 150, 92], [164, 120, 68], [132, 94, 50], [100, 70, 36], [52, 34, 16]);

