export interface ItemSprites {
  /** Lado de cada sprite en píxeles (16). */
  size: number;
  /** Número de sprites (ITEM_SPRITES y, detrás, los de cada tipo de poción: Fase 7). */
  count: number;
  /** count · 16 · 16 · 4 bytes, sRGB, alpha 0/255. */
  rgba: Uint8Array;
}

type RGB = readonly [number, number, number];

/** Tinta: color y color de contorno (por defecto, el color oscurecido). */
interface Ink {
  c: RGB;
  o?: RGB;
  /** Sin contorno alrededor (hilos finos y claros, p. ej. la cuerda del arco). */
  bare?: boolean;
}

type Inks = Readonly<Record<string, Ink>>;

interface SpriteDef {
  rows: readonly string[];
  inks: Inks;
  /** Los huecos cerrados (p. ej. las anillas de las tijeras) quedan transparentes, sin contorno. */
  holes?: boolean;
}

const S = 16;

function ink(c: RGB, o?: RGB): Ink {
  return { c, o };
}

/** Rampa de 4 tonos ('1' brillo … '4' sombra) con su contorno. */
function ramp(c1: RGB, c2: RGB, c3: RGB, c4: RGB, o: RGB): Record<string, Ink> {
  return { '1': ink(c1, o), '2': ink(c2, o), '3': ink(c3, o), '4': ink(c4, o) };
}

function mixRGB(a: RGB, b: RGB, t: number): RGB {
  return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
}

function luma(c: RGB): number {
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
}

