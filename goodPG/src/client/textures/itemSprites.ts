const TOOL_RE = /^(wooden|stone|iron|golden|diamond|copper|netherite)_(pickaxe|axe|shovel|sword|hoe)$/; // Fase 6.5: cobre; 8.5: netherita
const ARMOR_RE = /^(leather|iron|golden|diamond|copper|netherite)_(helmet|chestplate|leggings|boots)$/;

/** Marcador para sprites que aún no tienen dibujo. */
const PLACEHOLDER: SpriteDef = {
  rows: Array.from({ length: S }, (_, y) =>
    Array.from({ length: S }, (_, x) => (x < 2 || x > 13 || y < 2 || y > 13 ? '.' : ((x >> 2) + (y >> 2)) & 1 ? 'a' : 'b')).join(''),
  ),
  inks: { a: { c: [200, 40, 200] }, b: { c: [30, 30, 30] } },
};

function spriteDef(name: string): SpriteDef {
  const tool = TOOL_RE.exec(name);
  if (tool) return toolSprite(tool[1], tool[2]);
  const armor = ARMOR_RE.exec(name);
  if (armor) return armorSprite(armor[1], armor[2]);
  const sign = SIGN_RE.exec(name);
  if (sign) return signSprite(sign[1]);
  const door = DOOR_RE.exec(name);
  if (door) return doorSprite(door[1]);
  const bed = BED_RE.exec(name);
  if (bed && name !== 'red_bed') {
    const def = bedSprite(bed[1]);
    if (def) return def;
  }
  const def = Object.prototype.hasOwnProperty.call(SPRITES, name) ? SPRITES[name] : undefined;
  if (!def) {
    console.warn('Sprite de objeto sin dibujo (se usa un marcador): ' + name);
    return PLACEHOLDER;
  }
  return def;
}

/** Dibuja un sprite con su contorno automático en `out` (desplazamiento `base`). */
function drawSprite(name: string, def: SpriteDef, out: Uint8Array, base: number): void {
  if (def.rows.length !== S) throw new Error(`Sprite ${name}: ${def.rows.length} filas`);
  const cell: (Ink | null)[] = new Array(S * S).fill(null);
  for (let y = 0; y < S; y++) {
    const row = def.rows[y];
    if (row.length !== S) throw new Error(`Sprite ${name}: fila ${y} de ${row.length} px`);
    for (let x = 0; x < S; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      const k = def.inks[ch];
      if (!k) throw new Error(`Sprite ${name}: tinta desconocida '${ch}'`);
      cell[y * S + x] = k;
    }
  }
  const at = (x: number, y: number): Ink | null => (x < 0 || y < 0 || x >= S || y >= S ? null : cell[y * S + x]);
  // Exterior: huecos transparentes conectados con el borde del sprite (4-vecindad).
  const outside = new Uint8Array(S * S);
  if (def.holes) {
    const stack: number[] = [];
    for (let k = 0; k < S; k++) stack.push(k, (S - 1) * S + k, k * S, k * S + S - 1);
    while (stack.length) {
      const i = stack.pop()!;
      if (outside[i] || cell[i]) continue;
      outside[i] = 1;
      const x = i % S;
      const y = (i - x) / S;
      if (x > 0) stack.push(i - 1);
      if (x < S - 1) stack.push(i + 1);
      if (y > 0) stack.push(i - S);
      if (y < S - 1) stack.push(i + S);
    }
  }
  for (let y = 0; y < S; y++) {
    for (let x = 0; x < S; x++) {
      const o = base + (y * S + x) * 4;
      const k = cell[y * S + x];
      if (k) {
        out[o] = k.c[0];
        out[o + 1] = k.c[1];
        out[o + 2] = k.c[2];
        out[o + 3] = 255;
        continue;
      }
      if (def.holes && !outside[y * S + x]) continue;
      // Contorno: vecino de figura más oscuro (arriba, izquierda, derecha, abajo).
      let best: Ink | null = null;
      let bestL = Infinity;
      let lit = true;
      for (const [dx, dy] of [
        [0, -1],
        [-1, 0],
        [1, 0],
        [0, 1],
      ] as const) {
        const n = at(x + dx, y + dy);
        if (!n || n.bare) continue;
        const oc = n.o ?? mixRGB(n.c, [0, 0, 0], 0.62);
        const l = luma(oc);
        if (l < bestL) {
          bestL = l;
          best = n;
        }
        // La figura queda arriba o a la izquierda: este borde está en sombra.
        if (dy < 0 || dx < 0) lit = false;
      }
      if (!best) continue;
      let oc = best.o ?? mixRGB(best.c, [0, 0, 0], 0.62);
      if (lit) oc = mixRGB(oc, best.c, 0.16);
      out[o] = Math.round(oc[0]);
      out[o + 1] = Math.round(oc[1]);
      out[o + 2] = Math.round(oc[2]);
      out[o + 3] = 255;
    }
  }
}

export function generateItemSprites(): ItemSprites {
  // Fase 7 (pociones): después de los de ITEM_SPRITES, un dibujo por forma y tipo de poción.
  const count = ITEM_SPRITES.length + POTION_VARIANTS.length;
  const layer = S * S * 4;
  const rgba = new Uint8Array(count * layer);
  for (let i = 0; i < ITEM_SPRITES.length; i++) {
    const name = ITEM_SPRITES[i];
    drawSprite(name, spriteDef(name), rgba, i * layer);
  }
  POTION_VARIANTS.forEach((v, k) => drawSprite(v.name, v.def, rgba, (ITEM_SPRITES.length + k) * layer));
  return { size: S, count, rgba };
}
