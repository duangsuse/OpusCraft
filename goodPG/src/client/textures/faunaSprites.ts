// es una tinta y '.' es transparente; el contorno lo añade itemSprites): frasco de cristal, frasco
// de miel, panal, conejo crudo y cocinado, piel de conejo, escama de armadillo y cepillo.

type RGB = readonly [number, number, number];

interface Ink {
  c: RGB;
  o?: RGB;
  bare?: boolean;
}

interface SpriteDef {
  rows: readonly string[];
  inks: Readonly<Record<string, Ink>>;
  holes?: boolean;
}

const ink = (c: RGB, o?: RGB): Ink => ({ c, o });

function ramp(c1: RGB, c2: RGB, c3: RGB, c4: RGB, o: RGB): Record<string, Ink> {
  return { '1': ink(c1, o), '2': ink(c2, o), '3': ink(c3, o), '4': ink(c4, o) };
}

/** Frasco: `fill(fila)` da la tinta del interior de cada fila (F cristal vacío, h miel). */
function bottle(fill: (row: number) => string): string[] {
  const rows = [
    '................',
    '.......kk.......',
    '......rrrr......',
    '.......gg.......',
    '.......gg.......',
    '......gFFg......',
    '.....gFFFFg.....',
    '....gFFFFFFg....',
    '...gFFFFFFFFg...',
    '...gFFFFFFFFg...',
    '...gFFFFFFFFg...',
    '...gFFFFFFFFg...',
    '...gFFFFFFFFg...',
    '....gFFFFFFg....',
    '.....gggggg.....',
    '................',
  ];
  return rows.map((r, y) => {
    let s = r.replace(/F/g, fill(y));
    // Brillo del cristal a la izquierda.
    if (y >= 7 && y <= 11) s = s.slice(0, 4) + 'W' + s.slice(5);
    return s;
  });
}

