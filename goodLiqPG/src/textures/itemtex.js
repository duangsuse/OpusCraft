export function paintItemTextures() {
  const out = {};
  const tools = { pickaxe: PICKAXE, axe: AXE, shovel: SHOVEL, hoe: HOE, sword: SWORD };
  for (const [tier, pal] of Object.entries(TIER)) {
    const p = { ...pal, ...STICK };
    for (const [tool, shape] of Object.entries(tools)) out[`${tier}_${tool}`] = build(`${tier}_${tool}`, shape, p);
  }
  const armor = { helmet: HELMET, chestplate: CHESTPLATE, leggings: LEGGINGS, boots: BOOTS };
  for (const [mat, pal] of Object.entries(ARMOR)) {
    for (const [piece, shape] of Object.entries(armor)) out[`${mat}_${piece}`] = build(`${mat}_${piece}`, shape, pal);
  }
  for (const [name, [rows, pal]] of Object.entries(S)) out[name] = build(name, rows, pal);
  return out;
}
