// Hand-painted 16x16 item sprites in the style of the vanilla Minecraft (Java 1.20) item textures.
// Pure JS (no DOM / canvas). Every sprite is a list of 16 palette-char strings of 16 chars each;
// '.' (or ' ') is transparent, every other char is looked up in the sprite's palette (hex colors).
// Tool / armour shapes are drawn once and recoloured per material tier, exactly like vanilla does.
//
//   import { paintItemTextures } from './itemtex.js';
//   const tex = paintItemTextures();   // { name: { w:16, h:16, data: Uint8ClampedArray(1024) } }

const W = 16, H = 16;

function hexRGB(h) {
  const n = parseInt(h.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

// Authoring mistakes (bad row length, unknown palette char) are recorded instead of thrown so one
// typo never takes the whole atlas down; tools/preview_items.mjs prints them.
const problems = [];
export function itemTextureProblems() { return problems.slice(); }

function build(name, rows, pal) {
  if (rows.length !== H) problems.push(`${name}: ${rows.length} rows`);
  const data = new Uint8ClampedArray(W * H * 4);
  const cache = {};
  for (let y = 0; y < H; y++) {
    const r = rows[y] || '';
    if (r.length !== W) problems.push(`${name}: row ${y} has ${r.length} chars`);
    for (let x = 0; x < W; x++) {
      const c = r[x];
      if (c === undefined || c === '.' || c === ' ') continue;
      const hex = pal[c];
      if (!hex) { problems.push(`${name}: unknown palette char '${c}' at ${x},${y}`); continue; }
      const rgb = cache[c] || (cache[c] = hexRGB(hex));
      const i = (y * W + x) * 4;
      data[i] = rgb[0]; data[i + 1] = rgb[1]; data[i + 2] = rgb[2]; data[i + 3] = 255;
    }
  }
  return { w: W, h: H, data };
}

